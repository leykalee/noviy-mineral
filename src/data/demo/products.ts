const DAY = 24 * 60 * 60 * 1000;
/** Фиксированная точка отсчёта: даты demo-каталога не должны «плыть» между сборками */
const EPOCH = Date.parse('2026-08-17T00:00:00.000Z');

export const products: Product[] = drafts.map(({ daysAgo, ...draft }, index) => {
  const created = new Date(EPOCH - daysAgo * DAY).toISOString();
  return {
    ...draft,
    id: `p-${String(index + 1).padStart(4, '0')}`,
    // инвариант из п.28 ТЗ: уникальный экземпляр всегда в единственном числе
    stock: draft.uniquePiece ? 1 : draft.stock,
    createdAt: created,
    updatedAt: created,
  };
});

export const productById = new Map(products.map((p) => [p.id, p]));
export const productBySlug = new Map(products.map((p) => [p.slug, p]));
